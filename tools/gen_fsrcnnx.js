#!/usr/bin/env node
// Turns the FSRCNNX mpv user shader (app/src/shaders/third_party/, igv, LGPL-3.0)
// into Vulkan compute passes for the Picture settings' AI upscaler:
//
//   app/src/shaders/fsrcnnx/pass_NN.comp   one network layer each, weights unchanged
//   app/src/shaders/fsrcnnx/passes.inc     the pass table main.cpp includes
//
// Every layer runs at the stream's size and writes an RGBA16F image named as in
// the mpv shader (FEATURE1, MODEL21, ...). mpv's final "aggregation" hook (the
// 2x pixel shuffle) is not converted: fsrcnnx_out.comp does it and also puts
// the colour back. Run after updating the .glsl: node tools/gen_fsrcnnx.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', 'app', 'src', 'shaders');
const source = path.join(root, 'third_party', 'FSRCNNX_x2_8-0-4-1.glsl');
const outDir = path.join(root, 'fsrcnnx');
const text = fs.readFileSync(source, 'utf8').replace(/\r\n/g, '\n');

// Split into hooks: the //! header lines, then the body up to the next //!HOOK.
const hooks = [];
for (const chunk of text.split(/^(?=\/\/!HOOK)/m).slice(1)) {
  const lines = chunk.split('\n');
  const meta = { binds: [], body: [] };
  let i = 0;
  for (; i < lines.length && lines[i].startsWith('//!'); i++) {
    const [key, ...rest] = lines[i].slice(3).split(' ');
    const value = rest.join(' ');
    if (key === 'BIND') meta.binds.push(value);
    else meta[key.toLowerCase()] = value;
  }
  meta.body = lines.slice(i).join('\n').trim();
  hooks.push(meta);
}

const layers = hooks.filter(h => !h.width);   // skip the 2x aggregation hook
if (layers.length === 0) throw new Error('no layers found in ' + source);

fs.mkdirSync(outDir, { recursive: true });
for (const f of fs.readdirSync(outDir)) fs.unlinkSync(path.join(outDir, f));

const table = [];
layers.forEach((h, n) => {
  if (h.binds.length > 3) throw new Error(`${h.desc}: more than 3 inputs`);
  if (h.components !== '4') throw new Error(`${h.desc}: expected 4 components`);
  const name = `pass_${String(n + 1).padStart(2, '0')}`;
  const defines = h.binds.map((b, k) =>
    b === 'LUMA'
      ? `#define LUMA_texOff(o) fetch_(in${k}, vec2(o)).x`
      : `#define ${b}_texOff(o) fetch_(in${k}, vec2(o))`).join('\n');
  const glsl = `#version 450
// Generated by tools/gen_fsrcnnx.js from third_party/FSRCNNX_x2_8-0-4-1.glsl
// (FSRCNNX by igv, LGPL-3.0). Layer: ${h.desc}. Do not edit.
layout(local_size_x = 16, local_size_y = 16) in;
layout(binding = 0, rgba16f) uniform writeonly image2D dst;
layout(binding = 1) uniform sampler2D in0;
layout(binding = 2) uniform sampler2D in1;
layout(binding = 3) uniform sampler2D in2;
layout(push_constant) uniform Params { ivec2 size; } p;

ivec2 at_;
vec4 fetch_(sampler2D s, vec2 o) { return texelFetch(s, clamp(at_ + ivec2(o), ivec2(0), p.size - 1), 0); }
${defines}

${h.body}

void main()
{
    at_ = ivec2(gl_GlobalInvocationID.xy);
    if (at_.x >= p.size.x || at_.y >= p.size.y) return;
    imageStore(dst, at_, hook());
}
`;
  fs.writeFileSync(path.join(outDir, name + '.comp'), glsl);
  table.push({ name, desc: h.desc, save: h.save, binds: h.binds });
});

const inc = [
  '// Generated by tools/gen_fsrcnnx.js: the FSRCNNX layers, in order. Do not edit.',
  ...table.map(t => `static const uint32_t kFsrcnnx_${t.name}[] =\n#include "shaders/fsrcnnx/${t.name}.spv.inc"\n;`),
  'static const FsrcnnxLayer kFsrcnnxLayers[] = {',
  ...table.map(t => {
    const b = [0, 1, 2].map(k => (t.binds[k] ? `"${t.binds[k]}"` : 'nullptr')).join(', ');
    return `    {"${t.desc}", kFsrcnnx_${t.name}, sizeof(kFsrcnnx_${t.name}), "${t.save}", {${b}}},`;
  }),
  '};',
  '',
].join('\n');
fs.writeFileSync(path.join(outDir, 'passes.inc'), inc);
console.log(`${table.length} layers -> ${path.relative(process.cwd(), outDir)}`);
for (const t of table) console.log(`  ${t.name}  ${t.desc.padEnd(22)} ${t.binds.join('+')} -> ${t.save}`);
